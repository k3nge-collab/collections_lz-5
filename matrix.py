import numpy as np
# вводим размеры матрицы
r = int(input("Введите количество строк N: "))
s = int(input("Введите количество столбцов M: "))
f = np.random.randint(1, 10, size=(r, s)) # создаем рандомную матрицу из чисел(с помощью randint  программа сама подберет рандомные числа)
print("Исходная матрица:")
print(f)
c = f.T # транспонированная матрица (c помощью T мы можем найти транспонированную матрицу)
print("Транспонированная матрица:")
print(s)
if r == s: #проверяем квадратная матрица или нет
    d_orig = np.linalg.det(f) # определитель первой
    d_trans = np.linalg.det(c) # определитель второй
    print("Определитель исходной матрицы:", d_orig)
    print("Определитель транспонированной матрицы:", d_trans) 
    if d_orig == d_trans: # сравниваем
        print("Определители равны ")
    else:
        print("Определители разные ")
else:
    print("Матрица не квадратная, определитель посчитать нельзя")