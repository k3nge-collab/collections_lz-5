import matplotlib.pyplot as plt  # Подключаем инструмент для построения графиков
import numpy as np  # Задействуем библиотеку для математических расчетов
x = np.array([1, 2, 3, 4, 5, 6, 7])  # Задаем опорные точки для horizontal оси
# Рассчитываем координаты Y для каждого математического уравнения
y_x2 = x ** 2
y_x3 = x ** 3
y_ex = np.exp(x)
y_ln = np.log(x)
plt.figure('графики')  # Создаем холст для визуализации данных
# Отображаем кривые, используя понятные названия цветов на английском
plt.plot(x, y_x2, color='tomato', marker='s', label='x^2')         # Томатно-красный
plt.plot(x, y_ex, color='gold', marker='^', label='e^x')           # Золотой
plt.plot(x, y_ln, color='limegreen', marker='o', label='ln(x)')    # Ярко-лиственный зеленый
plt.plot(x, y_x3, color='dodgerblue', marker='x', label='x^3')     # Насыщенный голубой
plt.xlabel('Ось X')  # Задаем подпись для горизонтальной шкалы
plt.ylabel('Ось Y')  # Задаем подпись для вертикальной шкалы
plt.grid(True)  # Включаем отображение фоновой координатной сетки
plt.legend()  # Выводим на экран окошко с описанием маркеров
plt.show()  # Выводим готовый результат на экран
